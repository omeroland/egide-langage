#!/usr/bin/env python3
"""Generates the token declarations shared by the lexer, the Menhir parser and the token printer
(tokens.ml, token_decls.mly, token_table.ml).
Single source of truth for keywords and punctuation (spec/02-lexical-structure.md LEX-021, LEX-060).
Run: python3 tools/gen/tokens.py  (writes compiler/lib/syntax/tokens.ml, token_decls.mly and token_table.ml)"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

KEYWORDS = ["and","as","break","case","comptime","continue","defer","dyn","elif","else","enum","false","fn","for",
 "given","if","impl","import","in","inout","let","loop","match","module","new","not","or","pub","return","self",
 "Self","struct","take","trait","true","type","unsafe","using","var","where","while","with","yield"]

def kw_token(k):
    return "KW_SELF_TYPE" if k == "Self" else "KW_" + k.upper()

PUNCT = [  # (text, token) — longest first is handled by sedlex's longest match
 ("**","STARSTAR"),("==","EQEQ"),("!=","NEQ"),("<=","LE"),(">=","GE"),("+=","PLUSEQ"),("-=","MINUSEQ"),
 ("*=","STAREQ"),("/=","SLASHEQ"),("%=","PERCENTEQ"),("&=","AMPEQ"),("|=","PIPEEQ"),("^=","CARETEQ"),
 ("<<=","SHLEQ"),(">>=","SHREQ"),("<<","SHL"),(">>","SHR"),("->","ARROW"),("=>","FATARROW"),("|>","PIPEGT"),
 ("..=","DOTDOTEQ"),("..","DOTDOT"),
 ("+","PLUS"),("-","MINUS"),("*","STAR"),("/","SLASH"),("%","PERCENT"),("<","LT"),(">","GT"),("=","EQ"),
 ("&","AMP"),("|","PIPE"),("^","CARET"),("~","TILDE"),("?","QUESTION"),(".","DOT"),(",","COMMA"),
 (":","COLON"),("@","AT"),("(","LPAREN"),(")","RPAREN"),("[","LBRACKET"),("]","RBRACKET"),("{","LBRACE"),
 ("}","RBRACE")]

VALUED = [("IDENT","string"),("INT","string"),("FLOAT","string"),("DURATION","string * string"),("STRING","string"),("RAW_STRING","string"),("BYTES","string"),("CHAR","Uchar.t"),("TEMPLATE","template")]
LAYOUT = ["NEWLINE","INDENT","DEDENT","EOF"]


# The token type is written here, not by Menhir (--only-tokens), because LEX-055 makes it recursive: a TEMPLATE token
# holds the token streams of its interpolations. Menhir only declares the terminals (token_decls.mly).
TEMPLATE_TYPES = """
and template = { prefix : string; parts : part list }
(* LEX-055: the prefix (f, sql, ...) and the parts in source order. *)

and part =
  | Tpl_lit of string
    (* literal text, raw, doubled braces collapsed to one brace, dedented for a triple-quoted template *)
  | Tpl_interp of interp

and interp = {
  open_pos : Lexing.position; (* the opening brace *)
  close_pos : Lexing.position; (* just after the closing brace *)
  toks : (token * Lexing.position * Lexing.position) list;
      (* the expression, tokenised by the same lexer: no layout tokens, no spec *)
  spec : spec option;
}

and spec = { text : string; spec_pos : Lexing.position (* the first character after the colon *) }
"""

def main():
    syn = os.path.join(ROOT, "compiler/lib/syntax")
    with open(os.path.join(syn, "tokens.ml"), "w") as f:
        f.write("(* GENERATED by tools/gen/tokens.py — do not edit. *)\n")
        f.write("type token =\n")
        for name, ty in VALUED:
            f.write(f"  | {name} of ({ty})\n" if "*" in ty else f"  | {name} of {ty}\n")
        for k in KEYWORDS:
            f.write(f"  | {kw_token(k)}\n")
        for _, tok in PUNCT:
            f.write(f"  | {tok}\n")
        for t in LAYOUT:
            f.write(f"  | {t}\n")
        f.write(TEMPLATE_TYPES)
    with open(os.path.join(syn, "token_decls.mly"), "w") as f:
        f.write("(* GENERATED by tools/gen/tokens.py — do not edit. *)\n")
        for name, ty in VALUED:
            f.write(f"%token <{'Tokens.template' if name == 'TEMPLATE' else ty}> {name}\n")
        for k in KEYWORDS:
            f.write(f"%token {kw_token(k)}  (* {k} *)\n")
        for text, tok in PUNCT:
            f.write(f"%token {tok}  (* {text} *)\n")
        for t in LAYOUT:
            f.write(f"%token {t}\n")
        f.write("%%\n")
    with open(os.path.join(syn, "token_table.ml"), "w") as f:
        f.write("(* GENERATED by tools/gen/tokens.py — do not edit. *)\n")
        f.write("open Tokens\n\n")
        f.write("let keyword = function\n")
        for k in KEYWORDS:
            f.write(f'  | "{k}" -> Some {kw_token(k)}\n')
        f.write("  | _ -> None\n\n")
        f.write("let rec to_string = function\n")
        for name, _ in VALUED:
            if name == "DURATION":  # payload: (amount, unit), LEX-042
                f.write(f'  | {name} (a, u) -> Printf.sprintf "{name}(%S, %S)" a u\n')
            elif name == "TEMPLATE":  # payload: a template, LEX-055
                f.write(f'  | {name} t ->\n      Printf.sprintf "{name}(%S, [%s])" t.prefix (String.concat "; " (List.map part t.parts))\n')
            elif name == "CHAR":  # payload: a Unicode scalar value, LEX-054
                f.write(f'  | {name} c -> Printf.sprintf "{name}(U+%04X)" (Uchar.to_int c)\n')
            else:
                f.write(f'  | {name} s -> Printf.sprintf "{name}(%S)" s\n')
        for k in KEYWORDS:
            f.write(f'  | {kw_token(k)} -> "{k}"\n')
        for text, tok in PUNCT:
            f.write(f'  | {tok} -> {text!r}\n'.replace("'", '"'))
        for t in LAYOUT:
            f.write(f'  | {t} -> "{t}"\n')
        f.write("""
(* A literal part is shown as an OCaml string, an interpolation as its tokens in braces, with the spec after a colon. *)
and part = function
  | Tpl_lit s -> Printf.sprintf "%S" s
  | Tpl_interp i ->
      Printf.sprintf "{%s%s}"
        (String.concat " " (List.map (fun (t, _, _) -> to_string t) i.toks))
        (match i.spec with None -> "" | Some s -> Printf.sprintf " : %S" s.text)
""")

if __name__ == "__main__":
    main()
